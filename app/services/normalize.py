"""Нормализация текста игрока перед анализом.

Игроки и ники используют «декоративный» Unicode: полноширинные буквы (Ｏｓｋ), математические
жирные (𝐨𝐬𝐤), невидимые символы нулевой ширины внутри слов («о​ск»). Без нормализации
не срабатывают ключевые слова, извлечение пунктов правил и определение языка.
"""
import unicodedata


def normalize_text(text: str) -> str:
    """NFKC (сводит совместимые формы к обычным буквам и цифрам) + удаление невидимых
    форматирующих символов (категория Cf: zero-width, управление направлением текста)."""
    text = unicodedata.normalize("NFKC", text)
    return "".join(ch for ch in text if unicodedata.category(ch) != "Cf")
